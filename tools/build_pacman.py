def bitmap(sprite_art: str) -> list[str]:
    """Split a multi-line ASCII bitmap string into non-empty rows."""
    return [row for row in sprite_art.strip("\n").split("\n") if row]


def sprite_path(rows: list[str], pixel_w: float = UNIT_PX, pixel_h: float = UNIT_PX) -> str:
    """Merge a `#` bitmap into a single SVG `<path>` centered on `(0, 0)`."""
    height_rows, width_cols = len(rows), max(len(row) for row in rows)
    x_origin, y_origin = -width_cols * pixel_w / 2, -height_rows * pixel_h / 2
    path_cmds: list[str] = []
    for row_idx, row in enumerate(rows):
        col_idx = 0
        while col_idx < len(row):
            if row[col_idx] != "#":
                col_idx += 1
                continue
            run_end = col_idx
            while run_end < len(row) and row[run_end] == "#":
                run_end += 1
            path_cmds.append(
                f"M{x_origin + col_idx * pixel_w:g} {y_origin + row_idx * pixel_h:g}"
                f"h{(run_end - col_idx) * pixel_w:g}v{pixel_h:g}h{-(run_end - col_idx) * pixel_w:g}z"
            )
            col_idx = run_end
    return "".join(path_cmds)


def mix(hex_start: str, hex_end: str, factor: float) -> str:
    """Linearly interpolate between two `#rrggbb` colors."""
    rgb_start = [int(hex_start[idx : idx + 2], 16) for idx in (1, 3, 5)]
    rgb_end = [int(hex_end[idx : idx + 2], 16) for idx in (1, 3, 5)]
    return "#" + "".join(f"{round(c0 + (c1 - c0) * factor):02x}" for c0, c1 in zip(rgb_start, rgb_end))


class Timeline:
    """Pac-Man's zigzag route across the 7 weekday rows with synchronized chaser keyframes."""

    def __init__(self, week_count: int, left: float, top: float) -> None:
        self.left = left
        self.top = top
        self.speed = PITCH / STEP_DURATION

        waypoints: list[tuple[float, float]] = []
        for weekday in range(7):
            cols = (0, week_count - 1) if weekday % 2 == 0 else (week_count - 1, 0)
            waypoints.extend(
                [
                    (self.cell_center_x(cols[0]), self.cell_center_y(weekday)),
                    (self.cell_center_x(cols[1]), self.cell_center_y(weekday)),
                ]
            )
        waypoints.append((CANVAS_W + (max(TRAIL_LAGS) + 2) * PITCH, self.cell_center_y(6)))
        self.points = waypoints

        self.distances = [0.0]
        for pt_a, pt_b in zip(waypoints, waypoints[1:]):
            self.distances.append(self.distances[-1] + abs(pt_b[0] - pt_a[0]) + abs(pt_b[1] - pt_a[1]))

        self.done_time = INTRO_DELAY + (self.distances[-1] + max(TRAIL_LAGS) * PITCH) / self.speed
        self.total_duration = self.done_time + OUTRO_HOLD

    def cell_center_x(self, col: int) -> float:
        """Return horizontal center coordinate of calendar column `col`."""
        return self.left + col * PITCH + CELL_SIZE / 2

    def cell_center_y(self, row: int) -> float:
        """Return vertical center coordinate of calendar weekday `row`."""
        return self.top + row * PITCH + CELL_SIZE / 2

    def key_time(self, seconds: float) -> str:
        """Convert `seconds` on the master clock into a clamped `0..1` SMIL keyTime string."""
        return f"{min(max(seconds / self.total_duration, 0.0), 1.0):.5f}"

    def eat_time(self, col: int, row: int) -> float:
        """Return the timestamp when Pac-Man's mouth reaches `(col, row)`."""
        segment_idx = row * 2
        distance = self.distances[segment_idx] + abs(self.cell_center_x(col) - self.points[segment_idx][0])
        return INTRO_DELAY + max(0.0, distance - EAT_AHEAD) / self.speed

    def motion(self, lag_cells: int = 0) -> tuple[list[tuple[float, tuple[float, float]]], list[tuple[float, int]]]:
        """Compute translation keyframes and heading angles trailing Pac-Man by `lag_cells`."""
        lag_px = lag_cells * PITCH
        start_point = (self.points[0][0] - lag_px, self.points[0][1])
        route = [start_point] + self.points
        distances = [0.0] + [dist + lag_px for dist in self.distances]

        keyframes = [(0.0, start_point)]
        for dist, point in zip(distances, route):
            timestamp = INTRO_DELAY + dist / self.speed
            if (timestamp, point) != keyframes[-1]:
                keyframes.append((timestamp, point))

        headings: list[tuple[float, int]] = []
        for (timestamp, pt_a), (_, pt_b) in zip(keyframes, keyframes[1:]):
            if pt_a != pt_b:
                angle = 0 if pt_b[0] > pt_a[0] else 180 if pt_b[0] < pt_a[0] else 90
                headings.append((timestamp, angle))
        headings[0] = (0.0, headings[0][1])
        return keyframes, headings


def anim_translate(timeline: Timeline, keyframes: list[tuple[float, tuple[float, float]]]) -> str:
    """Emit linear SMIL `<animateTransform>` holding the terminal point until loop reset."""
    last_point = keyframes[-1][1]
    values = ";".join(f"{px:g},{py:g}" for _, (px, py) in keyframes) + f";{last_point[0]:g},{last_point[1]:g}"
    key_times = ";".join(timeline.key_time(ts) for ts, _ in keyframes) + ";1"
    return (
        f'<animateTransform attributeName="transform" type="translate" '
        f'values="{values}" keyTimes="{key_times}" dur="{timeline.total_duration:.3f}s" '
        f'repeatCount="indefinite"/>'
    )


def anim_discrete(timeline: Timeline, attr_name: str, values: list[str], times: list[float]) -> str:
    """Emit a stepped SMIL `<animate>` bound to `timeline`'s master clock."""
    return (
        f'<animate attributeName="{attr_name}" values="{";".join(values)}" '
        f'keyTimes="{";".join(timeline.key_time(ts) for ts in times)}" dur="{timeline.total_duration:.3f}s" '
        f'calcMode="discrete" repeatCount="indefinite"/>'
    )


def loop(attr_name: str, values: list[str], duration: float) -> str:
    """Emit an independent discrete repeating SMIL `<animate>` loop."""
    frame_count = len(values)
    key_times = ";".join(f"{idx / frame_count:.4f}" for idx in range(frame_count))
    return (
        f'<animate attributeName="{attr_name}" values="{";".join(values)}" '
        f'keyTimes="{key_times}" dur="{duration}s" calcMode="discrete" repeatCount="indefinite"/>'
    )


def build_placeholder_calendar() -> dict:
    """Create a 53-week blank fallback calendar ending today when `cache/calendar.json` is absent."""
    today = dt.date.today()
    days_since_sunday = (today.weekday() + 1) % 7
    last_sunday = today - dt.timedelta(days=days_since_sunday)
    first_sunday = last_sunday - dt.timedelta(weeks=52)

    weeks: list[list[dict | None]] = []
    for week_idx in range(53):
        slots: list[dict | None] = [None] * 7
        for weekday in range(7):
            current_day = first_sunday + dt.timedelta(weeks=week_idx, days=weekday)
            if current_day <= today:
                slots[weekday] = {"date": current_day.isoformat(), "count": 0, "level": 0}
        weeks.append(slots)
    return {"total": 0, "weeks": weeks}


def load_calendar() -> tuple[dict, bool]:
    """Load `cache/calendar.json` if present; otherwise return a placeholder calendar."""
    if not CALENDAR_SRC.exists():
        return build_placeholder_calendar(), True
    return json.loads(CALENDAR_SRC.read_text(encoding="utf-8")), False


def month_labels(weeks: list[list]) -> list[tuple[int, str]]:
    """Compute column positions for month labels, dropping cramped adjacent labels."""
    raw_labels: list[tuple[int, str]] = []
    previous_month = None
    for col_idx, week in enumerate(weeks):
        first_day = next((day for day in week if day), None)
        if not first_day:
            continue
        month_num = dt.date.fromisoformat(first_day["date"]).month
        if month_num != previous_month:
            raw_labels.append((col_idx, MONTH_NAMES[month_num - 1]))
            previous_month = month_num
    return [
        label
        for idx, label in enumerate(raw_labels)
        if idx + 1 == len(raw_labels) or raw_labels[idx + 1][0] - label[0] >= 3
    ]


def build_board(theme_name: str, calendar: dict) -> str:
    """Build the complete animated Pac-Man contribution SVG for `theme_name`."""
    palette = THEMES[theme_name]
    weeks = calendar["weeks"]
    level_ramp = [mix(palette["bg"], palette["fg"], ratio) for ratio in LEVEL_MIX]

    grid_left = MARGIN + LABEL_COL
    header_y = MARGIN + HEADER_FONT
    months_y = header_y + 26
    grid_top = months_y + 8
    grid_bottom = grid_top + 6 * PITCH + CELL_SIZE
    legend_y = grid_bottom + 24
    svg_height = legend_y + MARGIN

    timeline = Timeline(len(weeks), grid_left, grid_top)
    cell_groups: list[str] = []
    sprite_groups: list[str] = []

    base_cells: list[str] = []
    for col_idx, week in enumerate(weeks):
        for row_idx, day in enumerate(week):
            if day:
                base_cells.append(f'<use href="#d" x="{grid_left + col_idx * PITCH:g}" y="{grid_top + row_idx * PITCH:g}"/>')
    cell_groups.append(f'<g fill="{level_ramp[0]}">{"".join(base_cells)}</g>')

    eaten_events: list[tuple[float, int]] = []
    for col_idx, week in enumerate(weeks):
        for row_idx, day in enumerate(week):
            if not day or not day["level"]:
                continue
            eat_ts = timeline.eat_time(col_idx, row_idx)
            eaten_events.append((eat_ts, day["count"]))
            cell_groups.append(
                f'<use href="#d" x="{grid_left + col_idx * PITCH:g}" y="{grid_top + row_idx * PITCH:g}" '
                f'fill="{level_ramp[day["level"]]}">'
                f'{anim_discrete(timeline, "visibility", ["visible", "hidden"], [0.0, eat_ts])}</use>'
            )

    clawd_layers = {
        layer_name: sprite_path(bitmap(art), *CLAWD_PX)
        for layer_name, art in (
            ("body", CLAWD_BODY),
            ("arms_down", CLAWD_ARMS_DOWN),
            ("arms_up", CLAWD_ARMS_UP),
            ("legs_a", CLAWD_LEGS_A),
            ("legs_b", CLAWD_LEGS_B),
            ("lids", CLAWD_LIDS),
        )
    }

    def alternate_layers(layer_a: str, layer_b: str, duration: float) -> str:
        return (
            f'<path d="{clawd_layers[layer_a]}">{loop("opacity", ["1", "0"], duration)}</path>'
            f'<path d="{clawd_layers[layer_b]}" opacity="0">{loop("opacity", ["0", "1"], duration)}</path>'
        )

    for lag_cells, trait, stride_dur in CAST:
        keyframes, _ = timeline.motion(lag_cells)
        body_parts = [f'<path d="{clawd_layers["body"]}"/>', alternate_layers("legs_a", "legs_b", stride_dur)]
        body_parts.append(
            alternate_layers("arms_down", "arms_up", WAVE_PERIOD)
            if trait == "wave"
            else f'<path d="{clawd_layers["arms_down"]}"/>'
        )
        if trait == "blink":
            body_parts.append(
                f'<path d="{clawd_layers["lids"]}" opacity="0"><animate attributeName="opacity" '
                f'values="0;1;0" keyTimes="0;0.93;0.98" dur="{BLINK_EVERY}s" '
                f'calcMode="discrete" repeatCount="indefinite"/></path>'
            )
        sprite_body = "".join(body_parts)
        if trait == "hop":
            sprite_body = (
                f'<g><animateTransform attributeName="transform" type="translate" '
                f'values="0,0;0,{-CLAWD_PX[1]:g}" keyTimes="0;0.5" dur="{stride_dur}s" '
                f'calcMode="discrete" repeatCount="indefinite"/>{sprite_body}</g>'
            )
        sprite_groups.append(
            f'<g>{anim_translate(timeline, keyframes)}<g fill="{CLAUDE_CORAL[theme_name]}">{sprite_body}</g></g>'
        )

    pac_keyframes, pac_headings = timeline.motion(0)
    rotation_anim = (
        f'<animateTransform attributeName="transform" type="rotate" '
        f'values="{";".join(str(angle) for _, angle in pac_headings)}" '
        f'keyTimes="{";".join(timeline.key_time(ts) for ts, _ in pac_headings)}" dur="{timeline.total_duration:.3f}s" '
        f'calcMode="discrete" repeatCount="indefinite"/>'
    )
    idle_vis = anim_discrete(timeline, "visibility", ["visible", "hidden"], [0.0, INTRO_DELAY])
    moving_vis = anim_discrete(timeline, "visibility", ["hidden", "visible"], [0.0, INTRO_DELAY])
    chomp_frames = "".join(
        f'<path d="{sprite_path(bitmap(art))}">'
        f'{loop("opacity", [str(val) for val in visibility_mask], CHOMP_PERIOD)}</path>'
        for art, visibility_mask in ((PAC_OPEN, (1, 0, 0, 0)), (PAC_HALF, (0, 1, 0, 1)), (PAC_SHUT, (0, 0, 1, 0)))
    )
    sprite_groups.append(
        f'<g>{anim_translate(timeline, pac_keyframes)}<g fill="{palette["key"]}">{rotation_anim}'
        f'<g>{idle_vis}<path d="{sprite_path(bitmap(PAC_OPEN))}"/></g>'
        f'<g visibility="hidden">{moving_vis}{chomp_frames}</g></g></g>'
    )

    eaten_events.sort()
    score_steps, running_score = [(0.0, 0)], 0
    for eat_ts, count in eaten_events:
        if count:
            running_score += count
            score_steps.append((eat_ts, running_score))

    score_width = len(f"{calendar['total']:,}")
    score_tspans: list[str] = []
    for idx, (step_ts, score_value) in enumerate(score_steps):
        next_ts = score_steps[idx + 1][0] if idx + 1 < len(score_steps) else None
        if len(score_steps) == 1:
            score_tspans.append(f'<tspan x="{MARGIN:g}">{score_value:>{score_width},}</tspan>')
            continue
        if idx == 0:
            vis_values, vis_times = ["visible", "hidden"], [0.0, next_ts]
        elif next_ts is None:
            vis_values, vis_times = ["hidden", "visible"], [0.0, step_ts]
        else:
            vis_values, vis_times = ["hidden", "visible", "hidden"], [0.0, step_ts, next_ts]
        score_tspans.append(
            f'<tspan x="{MARGIN:g}" visibility="{"visible" if idx == 0 else "hidden"}">'
            f'{anim_discrete(timeline, "visibility", vis_values, vis_times)}{score_value:>{score_width},}</tspan>'
        )
    words_x = MARGIN + score_width * HEADER_FONT * ADVANCE

    months_markup = "".join(
        f'<text x="{grid_left + col_idx * PITCH:g}" y="{months_y:g}">{month_name}</text>'
        for col_idx, month_name in month_labels(weeks)
    )
    days_markup = "".join(
        f'<text x="{MARGIN:g}" y="{timeline.cell_center_y(row_idx) + LABEL_FONT * 0.35:g}">{day_name}</text>'
        for row_idx, day_name in WEEKDAY_LABELS.items()
    )

    grid_right = grid_left + (len(weeks) - 1) * PITCH + CELL_SIZE
    more_width = 4 * LABEL_FONT * ADVANCE
    swatch_x = grid_right - more_width - 6 - (5 * PITCH - (PITCH - CELL_SIZE))
    swatches_markup = "".join(
        f'<rect x="{swatch_x + idx * PITCH:g}" y="{legend_y - CELL_SIZE + 3:g}" '
        f'width="{CELL_SIZE}" height="{CELL_SIZE}" rx="{CORNER_RADIUS}" fill="{level_ramp[idx]}"/>'
        for idx in range(5)
    )

    return f"""<?xml version='1.0' encoding='UTF-8'?>
<svg xmlns="http://www.w3.org/2000/svg" width="{CANVAS_W}px" height="{svg_height:g}px"
     font-family="ConsolasFallback,Consolas,Menlo,monospace">
<style>
@font-face {{
  src: local('Consolas'), local('Consolas Bold');
  font-family: 'ConsolasFallback';
  font-display: swap;
  size-adjust: 109%;
}}
text, tspan {{white-space: pre;}}
.px {{shape-rendering: crispEdges;}}
</style>
<defs><rect id="d" width="{CELL_SIZE}" height="{CELL_SIZE}" rx="{CORNER_RADIUS}"/></defs>
<rect width="{CANVAS_W}px" height="{svg_height:g}px" fill="{palette['bg']}" rx="15"/>
<text y="{header_y:g}" font-size="{HEADER_FONT}px" fill="{palette['fg']}">{"".join(score_tspans)}</text>
<text x="{words_x:g}" y="{header_y:g}" font-size="{HEADER_FONT}px" fill="{palette['fg']}"> contributions in the last year</text>
<g font-size="{LABEL_FONT}px" fill="{palette['dots']}">{months_markup}{days_markup}
<text x="{swatch_x - 6:g}" y="{legend_y:g}" text-anchor="end">Less</text>
<text x="{grid_right - more_width:g}" y="{legend_y:g}">More</text>
</g>
{swatches_markup}
{"".join(cell_groups)}
<g class="px">{"".join(sprite_groups)}</g>
</svg>
"""


def validate_smil(svg_markup: str) -> int:
    """Validate SMIL `<animate>` / `<animateTransform>` `keyTimes` invariants before writing SVG."""
    root = ET.fromstring(svg_markup.split("?>", 1)[1])
    validated_count = 0
    for element in root.iter():
        tag_name = element.tag.split("}")[-1]
        if tag_name not in ("animate", "animateTransform") or "keyTimes" not in element.attrib:
            continue
        validated_count += 1
        key_times = [float(val) for val in element.get("keyTimes").split(";")]
        values = element.get("values").split(";")
        location = f"{tag_name} {element.get('attributeName')} ({len(values)} values)"
        if len(key_times) != len(values):
            raise SystemExit(f"{location}: {len(key_times)} keyTimes for {len(values)} values")
        if key_times[0] != 0:
            raise SystemExit(f"{location}: first keyTime is {key_times[0]}, must be 0")
        if any(nxt < cur for cur, nxt in zip(key_times, key_times[1:])):
            raise SystemExit(f"{location}: keyTimes decrease")
        if key_times[-1] > 1:
            raise SystemExit(f"{location}: keyTime {key_times[-1]} past 1")
        if element.get("calcMode", "linear") != "discrete" and key_times[-1] != 1:
            raise SystemExit(f"{location}: interpolated animation must end at keyTime 1")
        if re.search(r"nan|inf", element.get("values"), re.I):
            raise SystemExit(f"{location}: non-finite value")
    return validated_count


def main() -> None:
    """Generate `pacman_dark.svg` and `pacman_light.svg` from `cache/calendar.json` or fallback."""
    calendar, is_placeholder = load_calendar()
    day_count = sum(1 for week in calendar["weeks"] for day in week if day)
    source_note = "placeholder (cache/calendar.json not fetched yet)" if is_placeholder else "cache/calendar.json"
    print(f"calendar : {len(calendar['weeks'])} weeks, {day_count} days, {calendar['total']} contributions [{source_note}]")
    for theme_name in THEMES:
        svg_markup = build_board(theme_name, calendar)
        checked = validate_smil(svg_markup)
        out_path = ROOT / f"pacman_{theme_name}.svg"
        out_path.write_text(svg_markup, encoding="utf-8")
        print(f"wrote {out_path.name} ({out_path.stat().st_size:,} bytes, {checked} animations validated)")


if __name__ == "__main__":
    main()
